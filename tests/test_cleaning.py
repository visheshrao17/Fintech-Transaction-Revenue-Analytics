class TestRowCountPreservation:
    def test_cleaned_retains_all_rows(self, raw_df, cleaned_output):
        """Cleaning must NOT silently delete any rows."""
        cleaned, _, _ = cleaned_output
        assert len(cleaned) == len(raw_df), (
            f"Row count changed: raw={len(raw_df)}, cleaned={len(cleaned)}"
        )

    def test_source_not_modified(self, raw_df, cleaned_output):
        """The raw DataFrame must not be mutated."""
        cleaned, _, _ = cleaned_output
        # Check that 'flag_duplicate' was NOT added to the original
        assert "flag_duplicate" not in raw_df.columns

    def test_output_rows_equals_input_rows(self, raw_df, cleaned_output):
        _, _, report = cleaned_output
        assert report["output_rows"] == len(raw_df)


