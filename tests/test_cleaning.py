class TestDerivedColumns:
    def test_day_of_sim_range(self, cleaned_output):
        cleaned, _, _ = cleaned_output
        assert cleaned["day_of_sim"].min() >= 1
        assert cleaned["day_of_sim"].max() <= 31

    def test_hour_of_day_range(self, cleaned_output):
        cleaned, _, _ = cleaned_output
        assert cleaned["hour_of_day"].min() >= 0
        assert cleaned["hour_of_day"].max() <= 23

    def test_amount_band_not_all_null(self, cleaned_output):
        cleaned, _, _ = cleaned_output
        non_null = cleaned["amount_band"].notna().sum()
        # Most amount bands should be populated
        assert non_null > len(cleaned) * 0.95

    def test_fraud_label_values(self, cleaned_output):
        cleaned, _, _ = cleaned_output
        assert set(cleaned["fraud_label"].dropna().unique()).issubset(
            {"Legitimate", "Fraudulent"}
        )

    def test_is_large_transaction_boolean(self, cleaned_output):
        cleaned, _, _ = cleaned_output
        assert cleaned["is_large_transaction"].dtype in (bool, np.bool_)


