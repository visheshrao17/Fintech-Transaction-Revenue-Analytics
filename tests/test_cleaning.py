class TestCleanedSchema:
    def test_original_columns_preserved(self, cleaned_output):
        cleaned, _, _ = cleaned_output
        expected = ["step", "type", "amount", "nameOrig", "nameDest",
                    "isFraud", "isFlaggedFraud"]
        for col in expected:
            assert col in cleaned.columns, f"Source column '{col}' missing from cleaned output"

    def test_flag_columns_present(self, cleaned_output):
        cleaned, _, _ = cleaned_output
        flag_cols = ["flag_duplicate", "flag_missing_critical", "flag_negative_amount",
                     "flag_zero_amount", "flag_invalid_step", "flag_invalid_type",
                     "flag_orig_balance_mismatch", "flag_dest_balance_mismatch",
                     "flag_negative_balance", "any_quality_flag"]
        for col in flag_cols:
            assert col in cleaned.columns, f"Flag column '{col}' missing"

    def test_derived_columns_present(self, cleaned_output):
        cleaned, _, _ = cleaned_output
        derived = ["day_of_sim", "hour_of_day", "amount_band",
                   "is_large_transaction", "fraud_label"]
        for col in derived:
            assert col in cleaned.columns, f"Derived column '{col}' missing"

    def test_flag_columns_are_boolean(self, cleaned_output):
        cleaned, _, _ = cleaned_output
        flag_cols = [c for c in cleaned.columns if c.startswith("flag_")]
        for col in flag_cols:
            assert cleaned[col].dtype in (bool, np.bool_), (
                f"Flag column '{col}' should be boolean, got {cleaned[col].dtype}"
            )


