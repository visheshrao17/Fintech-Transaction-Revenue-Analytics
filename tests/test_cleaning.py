class TestQualityReport:
    def test_report_has_required_keys(self, cleaned_output):
        _, _, report = cleaned_output
        required_keys = [
            "input_rows", "output_rows", "flagged_rows", "flagged_pct",
            "clean_rows", "duplicate_rows", "negative_amount_rows",
        ]
        for key in required_keys:
            assert key in report, f"Report missing key: '{key}'"

    def test_flagged_plus_clean_equals_total(self, cleaned_output):
        _, _, report = cleaned_output
        assert report["flagged_rows"] + report["clean_rows"] == report["output_rows"]

    def test_flagged_pct_in_range(self, cleaned_output):
        _, _, report = cleaned_output
        assert 0.0 <= report["flagged_pct"] <= 100.0


# ---------------------------------------------------------------------------
# Reproducibility
# ---------------------------------------------------------------------------


class TestReproducibility:
    def test_pipeline_is_idempotent(self, raw_df):
        """Running the pipeline twice on the same input should yield identical results."""
        cleaned1, _, report1 = clean_paysim(raw_df)
        cleaned2, _, report2 = clean_paysim(raw_df)
        assert report1 == report2
        pd.testing.assert_frame_equal(
            cleaned1.reset_index(drop=True),
            cleaned2.reset_index(drop=True),
        )
